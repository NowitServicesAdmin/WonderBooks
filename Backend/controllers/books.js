const STAGES = [
  "starting", // placeholder only - photos not uploaded yet (not resumable)
  "characters_saved", // photos on S3 + story settings saved
  "bible_done", // Character Bible + reference images saved
  "story_saved", // title + pages (text) saved
  "plan_saved", // image prompts saved
];
const stageReached = (current, target) =>
  STAGES.indexOf(current || "starting") >= STAGES.indexOf(target);

// Share of the whole book that is done, for the progress bar on Home / My Books.
// Every step of the job moves it (not only finished pages), so it no longer
// sits at 5% through the character, story and prompt steps and then jumps.
//   0-50 %  : photos, Character Bible + references, story text, image prompts
//   50-99 % : cover + page illustrations (each one is an equal share)
//   100 %   : only when the book is marked completed
const STAGE_PROGRESS = {
  starting: 3,
  characters_saved: 8,
  bible_done: 28,
  story_saved: 42,
  plan_saved: 50,
};
const computeBookProgress = (b) => {
  if (b.status === "completed") return 100;
  if (b.status === "failed") return 0;

  const base = STAGE_PROGRESS[b.stage || "starting"] ?? STAGE_PROGRESS.starting;
  if (!stageReached(b.stage, "plan_saved")) return base;

  const pages = b.pages || [];
  const units = pages.length + 1; // every page + the cover
  const done =
    pages.filter((p) => p.status === "completed").length +
    (b.coverImageUrl ? 1 : 0);

  return Math.min(99, Math.round(base + (done / units) * (99 - base)));
};

