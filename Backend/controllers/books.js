const startHeartbeat = (bookId) => {
  const beat = () =>
    book
      .updateOne(
        { _id: bookId, status: "generating" },
        { $set: { lastProgressAt: new Date(), workerId: INSTANCE_ID } },
      )
      .catch(() => {}); // a missed beat is harmless

  beat();
  const timer = setInterval(beat, HEARTBEAT_MS);
  return () => clearInterval(timer);
};

