// RESUME SUPPORT
// A book is generated by a background job that lives in this process. If the
// server stops, the job dies with it. To survive that:
//   1. every step saves a checkpoint (`stage`) on the book,
//   2. a heartbeat (`lastProgressAt`) proves the job is still alive,
//   3. a sweep finds "generating" books whose heartbeat stopped, claims them
//      atomically and continues from the last checkpoint.
// ---------------------------------------------------------------------------
